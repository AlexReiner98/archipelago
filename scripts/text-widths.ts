// The width table the server measures text by when it draws a picture's first frame (src/text-widths.ts): each
// character's advance in the house style's typeface at 100 px, measured as a page's canvas measures it.
//   node scripts/text-widths.ts > src/text-widths.ts
// Measured on Windows (Segoe UI); a reader elsewhere sees the frame the drawing then lays out with their own fonts.

import { readFileSync } from 'node:fs';
import { join } from 'node:path';
import { open } from '../test/browser.ts';

const pack = JSON.parse(readFileSync(join(import.meta.dirname, '..', 'packs', 'core', 'pack.json'), 'utf8'));
const font: string = pack.styles.find((s: { id: string }) => s.id === 'core.house').props.font;
const chars = [...Array.from({ length: 95 }, (_, n) => String.fromCharCode(32 + n)), ...Array.from({ length: 96 }, (_, n) => String.fromCharCode(160 + n)), ...'‘’“”–—…·•→←×€'].join('');
const page = await open('about:blank');
const widths = await page.evaluate<Record<string, number>>(`(() => {
  const c = document.createElement('canvas').getContext('2d');
  c.font = ${JSON.stringify(`100px ${font}`)};
  return Object.fromEntries([...${JSON.stringify(chars)}].map((ch) => [ch, Math.round(c.measureText(ch).width * 100) / 100]));
})()`);
page.close();
const other = Math.round((Object.values(widths).reduce((a, b) => a + b, 0) / Object.keys(widths).length) * 100) / 100;
console.log(`// Generated by scripts/text-widths.ts: each character's advance at 100 px in the house style's typeface, as a
// page's canvas measures it on Windows. The server measures a first frame's text by it (src/published-frames.ts).

export const FONT = ${JSON.stringify(font)};
/** A character not in the table is this wide. */
export const OTHER = ${other};
export const WIDTHS: Record<string, number> = ${JSON.stringify(widths)};
`);
process.exit(0);
