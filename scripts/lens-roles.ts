// The one bridge from the theme to a drawing's colour roles (round 6, the palette): the house style's `roles` (packs/canvas/pack.json,
// each role the name of a theme colour) written once as the --ln-<role> custom properties three stylesheets used to copy by hand:
// the app (packs/surface/page/style.css), a picture in a published document (doc-lens.css) and the baked reader page
// (packs/reader/public/baked.css). `node scripts/lens-roles.ts` writes each between its markers; test/lens-roles.test.ts says they agree.

import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const root = join(import.meta.dirname, '..');
export const TARGETS = [
  { file: 'packs/surface/page/style.css', over: {} as Record<string, string> },
  { file: 'packs/surface/page/doc-lens.css', over: {} as Record<string, string> },
  // The reader page stands on its own ground, ink and line.
  { file: 'packs/reader/public/baked.css', over: { sea: 'var(--reader-page, var(--bg))', inner: 'var(--reader-page, var(--bg))', line: 'var(--reader-line, var(--edge))', text: 'var(--reader-ink, var(--text))', muted: 'var(--reader-muted, var(--muted))' } as Record<string, string> },
];
export const BEGIN = '/* roles:begin (generated by scripts/lens-roles.ts from the house style\'s roles) */', END = '/* roles:end */';

/** The house style's roles: role → theme name. */
export const rolesOf = (): Record<string, string> => JSON.parse(readFileSync(join(root, 'packs/canvas/pack.json'), 'utf8')).styles.find((s: { id: string }) => s.id === 'core.house').props.roles;

/** The declarations of every role, a line of four, with what a target says for itself in place of the theme's. */
export function declarations(over: Record<string, string>): string {
  const lines = Object.entries(rolesOf()).map(([role, name]) => `--ln-${role}: ${over[role] ?? `var(--${name.replaceAll('_', '-')})`};`);
  const rows: string[] = [];
  for (let i = 0; i < lines.length; i += 3) rows.push(`  ${lines.slice(i, i + 3).join(' ')}`);
  return rows.join('\n');
}

/** A stylesheet with its generated block made as the roles say. */
export function written(css: string, over: Record<string, string>): string {
  const at = css.indexOf(BEGIN), to = css.indexOf(END);
  if (at < 0 || to < 0) throw new Error('no roles block');
  return `${css.slice(0, at + BEGIN.length)}\n${declarations(over)}\n  ${css.slice(to)}`;
}

if (process.argv[1] === import.meta.filename) {
  for (const t of TARGETS) {
    const file = join(root, t.file), css = readFileSync(file, 'utf8');
    writeFileSync(file, written(css, t.over));
  }
}
